CREATE TABLE IF NOT EXISTS `taobao_customer_service_conversation_analysis_result` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '主键',
  `conversation_table_id` bigint DEFAULT NULL COMMENT '原始会话表ID，对应 taobao_customer_service_list.id',
  `msg_table_id` bigint DEFAULT NULL COMMENT '原始消息表ID，对应 taobao_customer_service_detail.id',
  `company_id` varchar(255) NOT NULL COMMENT '企业ID',
  `conversation_id` varchar(255) NOT NULL COMMENT '会话ID，对应 taobao_transfer.conversation_id / taobao_customer_service_list.tmp_conversation_id',
  `transfer_id` bigint DEFAULT NULL COMMENT '原始转人工记录ID，对应 taobao_transfer.id',
  `buyer_nick` varchar(255) DEFAULT NULL COMMENT '买家昵称快照',
  `seller_nick` varchar(255) DEFAULT NULL COMMENT '客服昵称快照',
  `raw_reason` varchar(255) DEFAULT NULL COMMENT '原始转人工原因，对应 taobao_transfer.reason',
  `scene_level1_code` varchar(64) DEFAULT NULL COMMENT '一级分类编码，例如 transfer_reason / customer_demand',
  `scene_level1_name` varchar(128) DEFAULT NULL COMMENT '一级分类名称',
  `scene_level2_code` varchar(128) DEFAULT NULL COMMENT '二级分类编码，例如 logistics_after_sale / upload_refusal',
  `scene_level2_name` varchar(255) DEFAULT NULL COMMENT '二级分类名称',
  `scene_level3_code` varchar(128) DEFAULT NULL COMMENT '三级分类编码，例如 modify_address / delivery_eta',
  `scene_level3_name` varchar(255) DEFAULT NULL COMMENT '三级分类名称',
  `analysis_source` varchar(32) NOT NULL DEFAULT 'rule' COMMENT '归因来源：rule/model/manual',
  `analysis_version` varchar(64) DEFAULT NULL COMMENT '归因规则或模型版本',
  `confidence` decimal(5,4) DEFAULT NULL COMMENT '归因置信度，0~1',
  `evidence_json` json DEFAULT NULL COMMENT '归因证据JSON，如命中关键词、命中规则、上下文摘要',
  `remark` varchar(500) DEFAULT NULL COMMENT '备注',
  `transfer_created_at` datetime DEFAULT NULL COMMENT '原始转人工时间，对应 taobao_transfer.created_at',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_company_conversation` (`company_id`,`conversation_id`),
  KEY `idx_transfer_id` (`transfer_id`),
  KEY `idx_company_scene_level1` (`company_id`,`scene_level1_code`),
  KEY `idx_company_scene_level2` (`company_id`,`scene_level1_code`,`scene_level2_code`),
  KEY `idx_company_scene_level3` (`company_id`,`scene_level1_code`,`scene_level2_code`,`scene_level3_code`),
  KEY `idx_company_transfer_created_at` (`company_id`,`transfer_created_at`),
  KEY `idx_company_raw_reason` (`company_id`,`raw_reason`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='客服聊天记录转人工原因分析结果表';
