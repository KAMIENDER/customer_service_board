CREATE TABLE IF NOT EXISTS `taobao_customer_service_scene_dictionary` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '主键',
  `company_id` varchar(255) NOT NULL DEFAULT '' COMMENT '企业ID，空字符串表示全局通用字典',
  `scene_category` varchar(32) NOT NULL COMMENT '分类场景，如 transfer / coverage',
  `scene_level1_code` varchar(64) NOT NULL COMMENT '一级分类编码',
  `scene_level1_name` varchar(128) NOT NULL COMMENT '一级分类名称',
  `scene_level2_code` varchar(128) DEFAULT NULL COMMENT '二级分类编码',
  `scene_level2_name` varchar(255) DEFAULT NULL COMMENT '二级分类名称',
  `scene_level3_code` varchar(128) DEFAULT NULL COMMENT '三级分类编码',
  `scene_level3_name` varchar(255) DEFAULT NULL COMMENT '三级分类名称',
  `leaf_level` tinyint NOT NULL DEFAULT 3 COMMENT '当前记录落到第几级，1/2/3',
  `sort_order` int NOT NULL DEFAULT 0 COMMENT '排序值，越小越靠前',
  `is_enabled` tinyint(1) NOT NULL DEFAULT 1 COMMENT '是否启用',
  `source` varchar(32) NOT NULL DEFAULT 'manual' COMMENT '来源：manual/import/system',
  `remark` varchar(500) DEFAULT NULL COMMENT '备注',
  `extra_json` json DEFAULT NULL COMMENT '扩展信息，例如展示配置、命中关键词等',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_company_category_scene_path` (`company_id`,`scene_category`,`scene_level1_code`,`scene_level2_code`,`scene_level3_code`),
  KEY `idx_category_level1` (`company_id`,`scene_category`,`scene_level1_code`,`sort_order`),
  KEY `idx_category_level2` (`company_id`,`scene_category`,`scene_level1_code`,`scene_level2_code`,`sort_order`),
  KEY `idx_category_level3` (`company_id`,`scene_category`,`scene_level1_code`,`scene_level2_code`,`scene_level3_code`,`sort_order`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='客服场景分类字典表，统一维护 code/name 与层级关系';
